/// Generate a C/C++ flake using `stdenv.mkDerivation`.
///
/// Detects CMake vs Make and generates the appropriate build recipe.
pub fn generate_c_flake(
    project_dir: &Path,
    output_dir: &Path,
    _style: FlakeStyle,
    source: &FlakeSource,
) -> Result<usize> {
    let project_name = project_dir
        .file_name()
        .and_then(|n| n.to_str())
        .unwrap_or("c-project");
    let flake_dir = output_dir.join("flakes").join(&project_name);
    fs::create_dir_all(&flake_dir)
        .with_context(|| format!("Failed to create flake dir: {}", flake_dir.display()))?;

    let has_cmake = project_dir.join("CMakeLists.txt").exists();
    let (native_inputs, build_phase) = if has_cmake {
        (
            "cmake pkg-config",
            r#"    buildPhase = ''
      cmake -DCMAKE_INSTALL_PREFIX=$out ..
      make
    '';
    installPhase = ''
      make install
    '';"#,
        )
    } else {
        (
            "pkg-config",
            r#"    buildPhase = ''
      make
    '';
    installPhase = ''
      make install
    '';"#,
        )
    };

    let (src_input, src_attr) = match source {
        FlakeSource::LocalDir => (String::new(), String::new()),
        FlakeSource::GitMirror { mirror_path, display: _ } => {
            let input = format!(
                r#"    src = {{
      url = "git+file://{mirror}";
      flake = false;
    }};
"#,
                mirror = mirror_path.display()
            );
            (input, "src".to_string())
        }
    };

    let params = if src_attr.is_empty() {
        "{ self, nixpkgs, flake-utils }".to_string()
    } else {
        format!("{{ self, nixpkgs, flake-utils, {src_attr} }}")
    };

    let src_reference = if src_attr.is_empty() {
        "./.".to_string()
    } else {
        format!("{src_attr}")
    };

    let package_nix = format!(
        r#"{{ pkgs, lib, src ? ./., ... }}:

pkgs.stdenv.mkDerivation {{
  pname = "{name}";
  version = "0.1.0";
  inherit src;

  nativeBuildInputs = with pkgs; [ {native_inputs} ];
  buildInputs = with pkgs; [ ];

{build_phase}

  doCheck = false;
}}
"#,
        name = project_name,
        native_inputs = native_inputs,
        build_phase = build_phase,
    );

    let flake_nix = format!(
        r#"# THIS FILE IS AUTO-GENERATED by cargo-vendormod (C/C++)
# DO NOT EDIT MANUALLY
#
# Project: {name}

{{
  description = "{name} - C/C++ project";

  inputs = {{
    nixpkgs.url = "github:NixOS/nixpkgs/nixpkgs-unstable";
    flake-utils.url = "github:numtide/flake-utils";
{src_input}  }};

  outputs =
    {params}:
    flake-utils.lib.eachDefaultSystem (
      system:
      let
        pkgs = import nixpkgs {{ inherit system; }};
        real_src = {src_reference};
      in
      {{
        packages = {{
          default = pkgs.callPackage ./package.nix {{ src = real_src; }};
          {name} = self.packages.${{system}}.default;
        }};

        devShells.default = pkgs.mkShell {{
          buildInputs = with pkgs; [ gcc pkg-config ];
        }};
      }}
    );
}}
"#,
        name = project_name,
        src_input = src_input,
        params = params,
        src_reference = src_reference,
    );

    fs::write(flake_dir.join("flake.nix"), &flake_nix)
        .with_context(|| format!("Failed to write flake.nix for {}", project_name))?;
    fs::write(flake_dir.join("package.nix"), &package_nix)
        .with_context(|| format!("Failed to write package.nix for {}", project_name))?;

    Ok(2)
}

