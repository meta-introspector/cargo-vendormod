// ── Generic dispatcher ──────────────────────────────────────────────────

/// Dispatch flake generation to the appropriate language generator.
///
/// Uses `lang_detect::detect_language()` to auto-detect the project language.
/// Falls back to Rust if no recognized language is found.
pub fn generate_multi_lang_flake(
    project_dir: &Path,
    output_dir: &Path,
    style: FlakeStyle,
    source: &FlakeSource,
    lang_override: Option<crate::lang_detect::Language>,
    nora: bool,
) -> Result<usize> {
    let lang = lang_override
        .unwrap_or_else(|| crate::lang_detect::detect_language(project_dir));

    match lang {
        crate::lang_detect::Language::Rust => {
            crate::crate_flake::generate_flake(project_dir, output_dir, None, style, None, source.clone(), nora)
        }
        crate::lang_detect::Language::Go => {
            generate_go_flake(project_dir, output_dir, style, source)
        }
        crate::lang_detect::Language::Python => {
            generate_python_flake(project_dir, output_dir, style, source)
        }
        crate::lang_detect::Language::C => {
            generate_c_flake(project_dir, output_dir, style, source)
        }
        crate::lang_detect::Language::JavaScript => {
            generate_js_flake(project_dir, output_dir, style, source)
        }
        crate::lang_detect::Language::Java => {
            generate_java_flake(project_dir, output_dir, style, source)
        }
        crate::lang_detect::Language::Unknown => {
            // Fallback to Rust (default behavior)
            crate::crate_flake::generate_flake(project_dir, output_dir, None, style, None, source.clone(), nora)
        }
    }
}
